module tb_top;

	import uvm_pkg::*;
	import fifo_uvm_pkg::*;

	logic clk = 1'b0;

	always #5ns clk = ~clk;

	fifo_if #(
		.NUM_FOLDS  (NUM_FOLDS),
		.FOLD_WIDTH (FOLD_WIDTH)
	) vif (
		.clk (clk)
	);

	checkpoint_fifo_buffer #(
		.DEPTH      (DEPTH),
		.NUM_FOLDS  (NUM_FOLDS),
		.FOLD_WIDTH (FOLD_WIDTH)
	) dut (
		.clk                       (vif.clk),
		.rst_n                     (vif.rst_n),
		.en_i                      (vif.en_i),
		.wr_en_i                   (vif.wr_en_i),
		.folded_history_i          (vif.folded_history_i),
		.rd_en_i                   (vif.rd_en_i),
		.misprediction_i           (vif.misprediction_i),
		.fifo_full_o               (vif.fifo_full_o),
		.fifo_empty_o              (vif.fifo_empty_o),
		.recovery_valid_o          (vif.recovery_valid_o),
		.recovery_folded_history_o (vif.recovery_folded_history_o)
	);

	initial begin
		vif.rst_n = 1'b0;
		repeat (3) @(negedge clk);
		vif.rst_n = 1'b1;
	end

	initial begin
		uvm_config_db#(virtual fifo_if #(NUM_FOLDS, FOLD_WIDTH))::set(null,"uvm_test_top.env.agent.*","vif",vif);
		run_test("fifo_test");
	end

endmodule