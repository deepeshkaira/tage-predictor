// interface

interface fifo_if #(
	parameter int NUM_FOLDS  = 7,
	parameter int FOLD_WIDTH = 23
  ) (
	input logic clk
  );
  
	// Reset and DUT inputs
	logic rst_n;
	logic en_i;
	logic wr_en_i;
	logic [FOLD_WIDTH-1:0] folded_history_i [0:NUM_FOLDS-1];
	logic rd_en_i;
	logic misprediction_i;
  
	// DUT outputs
	logic fifo_full_o;
	logic fifo_empty_o;
	logic recovery_valid_o;
	logic [FOLD_WIDTH-1:0] recovery_folded_history_o [0:NUM_FOLDS-1];
  
	clocking drv_cb @(negedge clk);
	  output en_i;
	  output wr_en_i;
	  output folded_history_i;
	  output rd_en_i;
	  output misprediction_i;
	endclocking
  
	clocking mon_cb @(posedge clk);
	  default input #0;
  
	  input rst_n;
	  input en_i;
	  input wr_en_i;
	  input folded_history_i;
	  input rd_en_i;
	  input misprediction_i;
  
	  input fifo_full_o;
	  input fifo_empty_o;
	  input recovery_valid_o;
	  input recovery_folded_history_o;
	endclocking
  
	modport DRIVER (
	  clocking drv_cb,
	  input rst_n
	);
  
	modport MONITOR (
	  clocking mon_cb
	);
  
	modport DUT (
	  input  clk,
	  input  rst_n,
	  input  en_i,
	  input  wr_en_i,
	  input  folded_history_i,
	  input  rd_en_i,
	  input  misprediction_i,
	  output fifo_full_o,
	  output fifo_empty_o,
	  output recovery_valid_o,
	  output recovery_folded_history_o
	);
  
endinterface

// sequence item
class fifo_item extends uvm_sequence_item;

	// Generated by sequences and driven into the DUT
	rand bit en;
	rand bit wr_en;
	rand bit rd_en;
	rand bit misprediction;
	rand bit [FOLD_WIDTH-1:0] data [0:NUM_FOLDS-1];

	// Captured by the monitor
	bit rst_n;
	bit full;
	bit empty;
	bit recovery_valid;
	bit [FOLD_WIDTH-1:0] recovery_data [0:NUM_FOLDS-1];

	// Mostly active traffic, with occasional global-enable stalls.
	constraint useful_c {
		en dist {
			1 := 9,
			0 := 1
		};
	}

	`uvm_object_utils_begin(fifo_item)
		`uvm_field_int(en,            UVM_DEFAULT)
		`uvm_field_int(wr_en,         UVM_DEFAULT)
		`uvm_field_int(rd_en,         UVM_DEFAULT)
		`uvm_field_int(misprediction, UVM_DEFAULT)
		`uvm_field_sarray_int(data,   UVM_DEFAULT)

		`uvm_field_int(rst_n,          UVM_DEFAULT | UVM_NOCOMPARE)
		`uvm_field_int(full,           UVM_DEFAULT | UVM_NOCOMPARE)
		`uvm_field_int(empty,          UVM_DEFAULT | UVM_NOCOMPARE)
		`uvm_field_int(recovery_valid, UVM_DEFAULT | UVM_NOCOMPARE)
		`uvm_field_sarray_int(
			recovery_data,
			UVM_DEFAULT | UVM_NOCOMPARE
		)
	`uvm_object_utils_end

	function new(string name = "fifo_item");
		super.new(name);
	endfunction

endclass

