		fifo_corner_seq corner;
		fifo_random_seq random_seq;

		phase.raise_objection(this);

			// corner = fifo_corner_seq::type_id::create("corner");
			// corner.start(env.agent.seqr);
			random_seq = fifo_random_seq::type_id::create("random_seq");
			random_seq.start(env.agent.seqr);

			// Allow the final driven item to be sampled and checked.
