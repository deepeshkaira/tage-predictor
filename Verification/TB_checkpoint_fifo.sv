class fifo_driver extends uvm_driver #(fifo_item);

	`uvm_component_utils(fifo_driver)

	virtual fifo_if #(NUM_FOLDS, FOLD_WIDTH) vif;

	function new(string name = "fifo_driver",uvm_component parent = null);
		super.new(name, parent);
	endfunction

	function void build_phase(uvm_phase phase);
		super.build_phase(phase);

		if (!uvm_config_db#(virtual fifo_if #(NUM_FOLDS, FOLD_WIDTH))::get(this, "", "vif", vif)) begin
			`uvm_fatal("FIFO/DRV/NOVIF","fifo_if was not configured")
		end
	endfunction

	task drive_idle();
		vif.drv_cb.en_i            <= 1'b0;
		vif.drv_cb.wr_en_i         <= 1'b0;
		vif.drv_cb.rd_en_i         <= 1'b0;
		vif.drv_cb.misprediction_i <= 1'b0;

		for (int i = 0; i < NUM_FOLDS; i++) begin
				vif.drv_cb.folded_history_i[i] <= '0;
			end
	endtask

	task drive_item(fifo_item item);
		vif.drv_cb.en_i            <= item.en;
		vif.drv_cb.wr_en_i         <= item.wr_en;
		vif.drv_cb.rd_en_i         <= item.rd_en;
		vif.drv_cb.misprediction_i <= item.misprediction;

		for (int i = 0; i < NUM_FOLDS; i++) begin
			vif.drv_cb.folded_history_i[i] <= item.data[i];
		end
	endtask

	task run_phase(uvm_phase phase);
		drive_idle();

		// Do not begin sequence traffic during reset.
		wait (vif.rst_n === 1'b1);

		forever begin
			seq_item_port.get_next_item(req);

			// drv_cb is triggered on the falling edge.
			@(vif.drv_cb);
			drive_item(req);

			seq_item_port.item_done();
		end
	endtask

endclass


class fifo_monitor extends uvm_component;

	`uvm_component_utils(fifo_monitor)
	virtual fifo_if #(NUM_FOLDS, FOLD_WIDTH) vif;
	uvm_analysis_port #(fifo_item) ap;

	function new(string name = "fifo_monitor",uvm_component parent = null);
		super.new(name, parent);
		ap = new("ap", this);
	endfunction

	function void build_phase(uvm_phase phase);
		super.build_phase(phase);

		if (!uvm_config_db#(virtual fifo_if #(NUM_FOLDS, FOLD_WIDTH))::get(this, "", "vif", vif)) begin
		`uvm_fatal(
			"FIFO/MON/NOVIF",
			"fifo_if was not configured"
		)
		end
	endfunction

	task run_phase(uvm_phase phase);
		fifo_item t;

		forever begin
			@(vif.mon_cb);

			t = fifo_item::type_id::create("observed");

			// Capture DUT inputs for this cycle.
			t.rst_n         = vif.mon_cb.rst_n;
			t.en            = vif.mon_cb.en_i;
			t.wr_en         = vif.mon_cb.wr_en_i;
			t.rd_en         = vif.mon_cb.rd_en_i;
			t.misprediction = vif.mon_cb.misprediction_i;

			// Capture DUT outputs after the rising-edge update.
			t.full           = vif.mon_cb.fifo_full_o;
			t.empty          = vif.mon_cb.fifo_empty_o;
			t.recovery_valid = vif.mon_cb.recovery_valid_o;

			for (int i = 0; i < NUM_FOLDS; i++) begin
				t.data[i] = vif.mon_cb.folded_history_i[i];
				t.recovery_data[i] = vif.mon_cb.recovery_folded_history_o[i];
			end

			ap.write(t);
		end
	endtask

endclass

// scoreboard
class fifo_scoreboard extends uvm_component;

	`uvm_component_utils(fifo_scoreboard)

	uvm_analysis_imp #(fifo_item, fifo_scoreboard) imp;

	typedef bit [FOLD_WIDTH-1:0] fold_entry_t [NUM_FOLDS];
	fold_entry_t model_q[$];

	int unsigned checked_cycles;

	function new(string name = "fifo_scoreboard",uvm_component parent = null);
		super.new(name, parent);
		imp = new("imp", this);
	endfunction

	function void write(fifo_item t);
		bit read_accept;
		bit write_accept;

		fold_entry_t popped;
		int old_size;

		// Reset the reference model and check reset outputs.
		if (t.rst_n !== 1'b1) begin
		model_q.delete();

		if (t.full !== 1'b0)
			`uvm_error("FIFO/SB/RESET","fifo_full_o is not 0 during reset"
			)

		if (t.empty !== 1'b1)
			`uvm_error("FIFO/SB/RESET","fifo_empty_o is not 1 during reset"
			)

		if (t.recovery_valid !== 1'b0)
			`uvm_error("FIFO/SB/RESET","recovery_valid_o is not 0 during reset"
			)

		for (int i = 0; i < NUM_FOLDS; i++) begin
			if (t.recovery_data[i] !== '0)
			`uvm_error("FIFO/SB/RESET_DATA",$sformatf("recovery fold[%0d] is not 0 during reset",i))
		end

		return;
		end

		old_size = model_q.size();

		read_accept = t.en && t.rd_en && (old_size != 0);

		write_accept = t.en && t.wr_en && ((old_size != DEPTH) || read_accept);

		// A simultaneous full read/write first removes the oldest
		// entry and then installs the replacement entry.
		if (read_accept)
		popped = model_q.pop_front();

		if (write_accept)
		model_q.push_back(t.data);

		if (t.empty !== (model_q.size() == 0))
		`uvm_error("FIFO/SB/EMPTY",$sformatf("empty=%0b expected=%0b model_size=%0d",t.empty,(model_q.size() == 0),model_q.size()))

		if (t.full !== (model_q.size() == DEPTH))
		`uvm_error("FIFO/SB/FULL",$sformatf("full=%0b expected=%0b model_size=%0d",t.full,(model_q.size() == DEPTH),model_q.size()))

		if (t.recovery_valid !== (read_accept && t.misprediction))
		`uvm_error("FIFO/SB/VALID",$sformatf("recovery_valid=%0b expected=%0b",t.recovery_valid,(read_accept && t.misprediction)))

		foreach (t.recovery_data[i]) begin
		if (read_accept && t.misprediction) begin
			if (t.recovery_data[i] !== popped[i])
			`uvm_error("FIFO/SB/DATA",$sformatf("fold[%0d]=%h expected=%h",i,t.recovery_data[i],popped[i]))
		end
		else if (t.recovery_data[i] !== '0) begin
			`uvm_error("FIFO/SB/ZERO",$sformatf("fold[%0d]=%h while recovery is invalid",i,t.recovery_data[i]))
		end
		end

		checked_cycles++;
	endfunction

	function void report_phase(uvm_phase phase);
		super.report_phase(phase);

		`uvm_info("FIFO/SB/SUMMARY",$sformatf("Checked %0d active FIFO cycles",checked_cycles),UVM_LOW)
	endfunction

endclass

// agent

class fifo_agent extends uvm_agent;

	`uvm_component_utils(fifo_agent)

	fifo_sequencer seqr;
	fifo_driver    drv;
	fifo_monitor   mon;

	function new(string name = "fifo_agent",uvm_component parent = null);
		super.new(name, parent);
	endfunction

	function void build_phase(uvm_phase phase);
		super.build_phase(phase);

		// Monitoring is needed for both active and passive agents.
		mon = fifo_monitor::type_id::create("mon",this);

		if (get_is_active() == UVM_ACTIVE) begin
			seqr = fifo_sequencer::type_id::create("seqr",this);
			drv = fifo_driver::type_id::create("drv",this);
		end
	endfunction

	function void connect_phase(uvm_phase phase);
		super.connect_phase(phase);

		if (get_is_active() == UVM_ACTIVE) begin
			drv.seq_item_port.connect(seqr.seq_item_export);
		end
	endfunction

endclass

